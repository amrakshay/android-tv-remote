    private fun keyFor(modulus: BigInteger): AdbKey {
        val public = KeyFactory.getInstance("RSA")
            .generatePublic(RSAPublicKeySpec(modulus, BigInteger.valueOf(65537)))
        return AdbKey(KeyPair(public, null))
    }

    @Test
    fun `public key matches what adb itself produces`() {
        val encoded = keyFor(modulus).encodePublicKey()
        assertEquals(4 + 4 + 256 + 256 + 4, encoded.size)
        assertEquals(adbEncoded, Base64.getEncoder().encodeToString(encoded))
    }

    @Test
    fun `little-endian conversion drops the sign byte`() {
        // A 2048-bit modulus always has its top bit set, so toByteArray() returns
        // 257 bytes with a leading zero. Reversing that unshifted puts every byte
        // one place out and the device rejects the key with no explanation.
        val value = BigInteger("FF00000000000000000000000000000000000000000000000000000000000001", 16)
        val le = AdbKey.littleEndian(value, 32)
        assertEquals(32, le.size)
        assertEquals(0x01, le[0].toInt() and 0xFF)
        assertEquals(0xFF, le[31].toInt() and 0xFF)
    }

    @Test
    fun `signature is PKCS1 over the SHA-1 DigestInfo and the raw token`() {
        val pair = KeyPairGenerator.getInstance("RSA").apply { initialize(2048) }.generateKeyPair()
        val key = AdbKey(pair)
        val token = ByteArray(20) { it.toByte() }

        // adbd verifies with RSA_verify(NID_sha1, token, …): the token is treated
        // as a digest already, so undoing the padding must give the prefix and
        // then the token itself, with no second hash in between.
        val recovered = Cipher.getInstance("RSA/ECB/PKCS1Padding").run {
            init(Cipher.DECRYPT_MODE, pair.public)
            doFinal(key.sign(token))
        }
        assertEquals(15 + 20, recovered.size)
        assertArrayEquals(token, recovered.copyOfRange(15, recovered.size))
        assertTrue(recovered.copyOfRange(0, 15).joinToString("") { "%02x".format(it) }
            .startsWith("3021300906052b0e03021a05000414"))
    }
