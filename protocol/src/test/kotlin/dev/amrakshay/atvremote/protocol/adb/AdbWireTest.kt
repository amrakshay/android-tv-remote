package dev.amrakshay.atvremote.protocol.adb

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.math.BigInteger
import java.security.KeyFactory
import java.security.KeyPair
import java.security.KeyPairGenerator
import java.security.spec.RSAPublicKeySpec
import java.util.Base64
import javax.crypto.Cipher

class AdbWireTest {

    @Test
    fun `header round trips`() {
        val payload = "shell:echo hi".toByteArray()
        val encoded = AdbWire.encode(AdbMessage(A_OPEN, 7, 0, payload))
        assertEquals(AdbWire.HEADER_SIZE + payload.size, encoded.size)

        val decoded = AdbWire.read(ByteArrayInputStream(encoded))
        assertEquals(A_OPEN, decoded.command)
        assertEquals(7, decoded.arg0)
        assertEquals(0, decoded.arg1)
        assertArrayEquals(payload, decoded.payload)
    }

    @Test
    fun `commands are little-endian ascii`() {
        // The constants are the four letters read back off the wire; getting the
        // byte order wrong here makes every message look like a framing error.
        assertEquals("CNXN", AdbMessage.commandName(A_CNXN))
        assertEquals("OPEN", AdbMessage.commandName(A_OPEN))
        assertEquals("OKAY", AdbMessage.commandName(A_OKAY))
        assertEquals("CLSE", AdbMessage.commandName(A_CLSE))
        assertEquals("WRTE", AdbMessage.commandName(A_WRTE))
        assertEquals("AUTH", AdbMessage.commandName(A_AUTH))
    }

    @Test
    fun `checksum is an unsigned byte sum`() {
        // 0xFF must count as 255, not -1. A signed sum is accepted by current
        // adbd and rejected by older images, which is the worst way to be wrong.
        assertEquals(255 + 1, AdbWire.checksum(byteArrayOf(0xFF.toByte(), 0x01)))
    }

    @Test
    fun `a corrupt magic is refused`() {
        val encoded = AdbWire.encode(AdbMessage(A_OKAY, 1, 2))
        encoded[20] = (encoded[20] + 1).toByte()
        assertThrows(AdbProtocolException::class.java) {
            AdbWire.read(ByteArrayInputStream(encoded))
        }
    }

    @Test
    fun `an absurd payload length is refused rather than allocated`() {
        val encoded = AdbWire.encode(AdbMessage(A_WRTE, 1, 2))
        // 0x7FFFFFFF bytes, which a trusting reader would try to allocate.
        encoded[12] = 0xFF.toByte(); encoded[13] = 0xFF.toByte()
        encoded[14] = 0xFF.toByte(); encoded[15] = 0x7F
        assertThrows(AdbProtocolException::class.java) {
            AdbWire.read(ByteArrayInputStream(encoded))
        }
    }
}

